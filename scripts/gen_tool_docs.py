"""Write the tool reference generated from the tool registry (ADR-0003).

python scripts/gen_tool_docs.py           # rewrite docs/tools.md
python scripts/gen_tool_docs.py --check   # exit 1 if the committed file differs from the code
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from gen_openapi import ROOT, write_or_check

TOOLS_MD = ROOT / "docs" / "tools.md"


def _type(prop: dict[str, Any]) -> str:
    b = next((b for b in prop.get("anyOf", [prop]) if b.get("type") != "null"), prop)
    if prop.get("writeOnly"):
        return "secret"
    if "enum" in b:
        titles = prop.get("x-enum-titles") or [None] * len(b["enum"])
        return "one of " + ", ".join(
            f"`{v}`" if t is None or t.lower() == str(v).lower() else f"`{v}` ({t})"
            for v, t in zip(b["enum"], titles, strict=True)
        )
    kind = b.get("type", "?")
    if kind == "array":  # list of models: its fields follow as `name[].field` rows
        return f"list, {b.get('minItems', 0)}..{b.get('maxItems')} entries"
    if kind in ("integer", "number"):
        lo = b.get("minimum", b.get("exclusiveMinimum"))
        hi = b.get("maximum", b.get("exclusiveMaximum"))
        return f"{kind} {lo}..{hi}"
    if kind == "string" and "maxLength" in b:
        return f"string, max {b['maxLength']} characters"
    return kind


def _options(schema: dict[str, Any]) -> list[str]:
    rows: list[str] = []

    def walk(s: dict[str, Any], prefix: str) -> None:
        required = set(s.get("required", []))
        for name, prop in s.get("properties", {}).items():
            ref = prop.get("$ref") or next(
                (b["$ref"] for b in prop.get("anyOf", []) if "$ref" in b), None
            )
            if ref:  # one level of nesting (registry rule)
                walk(schema["$defs"][ref.rsplit("/", 1)[-1]], f"{prefix}{name}.")
                continue
            if name in required:
                default = "required"
            elif "default" in prop:
                default = f"`{json.dumps(prop['default'])}`"
            else:
                default = ""
            title = prop.get("title", "").replace("|", "\\|")
            rows.append(f"| `{prefix}{name}` | {title} | {_type(prop)} | {default} |")
            item = prop.get("items", {}).get("$ref")
            if item:
                walk(schema["$defs"][item.rsplit("/", 1)[-1]], f"{prefix}{name}[].")

    walk(schema, "")
    if not rows:
        return ["No options."]
    return ["| Option | Title | Type | Default |", "|---|---|---|---|", *rows]


def _codes(codes: Any) -> str:
    return ", ".join(f"`{c}`" for c in sorted(codes)) or "none"


def render() -> str:
    from filex.registry import COMMON_ERRORS, RUNNER_ERRORS, discover

    tools = discover()
    out = [
        "# FileX tools",
        "",
        "<!-- Generated by scripts/gen_tool_docs.py from the tool registry. Do not edit. -->",
        "",
        "Every job may also fail with one of the common error codes: "
        + _codes(COMMON_ERRORS | RUNNER_ERRORS)
        + ". The API contract is [api/openapi.json](api/openapi.json).",
        "",
        "## Convert to any format (`convert`)",
        "",
        (
            "FileX picks the route over the converters below (ADR-0005): the cheapest chain of "
            "at most 4 steps among the workers online now, possibly across profiles. Each step "
            "runs with its tool's default options; every lossy step adds a `LOSSY_STEP` warning."
        ),
        "",
        (
            "- Preview: `GET /api/v1/convert/plan?from=<format>&to=<format>`; reachable pairs: "
            "`GET /api/v1/convert/targets`"
        ),
        "- Route: `POST /api/v1/convert/jobs` with `files` and a `target` part",
        "- No route: `422 NO_ROUTE`, `details.profiles` names the profiles that would create one",
    ]
    for category in sorted({t.category for t in tools.values()}):
        out += ["", f"## {category.capitalize()}"]
        for t in (t for t in tools.values() if t.category == category):
            f = t.files
            files = f"{f.min}" if f.min == f.max else f"{f.min} to {f.max}"
            if f.each:
                files += ", each processed on its own"
            out += [
                "",
                f"### {t.title} (`{t.id}`)",
                "",
                t.summary,
                "",
                f"- Route: `POST /api/v1/tools/{t.id}/jobs`",
                f"- Profile: `{t.group}`",
                f"- Input: {_codes(t.inputs)}, {files} files",
                f"- Output: {_codes(t.outputs)}",
            ]
            if t.converts:
                default = (
                    f"default: the `{t.target_option}` option"
                    if t.target_option
                    else "required unless the inputs convert to one format only"
                )
                out.append(f"- Target: the `target` part, one of the outputs ({default})")
            if t.keywords:
                out.append("- Keywords: " + ", ".join(t.keywords))
            out += [
                f"- Auxiliary file `{slot}`: {aux.title} ({_codes(aux.formats)}"
                + (")" if aux.required else ", optional)")
                for slot, aux in f.aux.items()
            ]
            out += [
                f"- Warnings: {_codes(t.warnings)}",
                f"- Errors: {_codes(t.errors)}",
                "",
                *_options(t.options_schema),
            ]
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None, path: Path = TOOLS_MD) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args(argv)
    return write_or_check(path, render(), args.check, "gen_tool_docs.py")


if __name__ == "__main__":
    sys.exit(main())
